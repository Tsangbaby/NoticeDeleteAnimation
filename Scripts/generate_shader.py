#!/usr/bin/env python3
"""Byte-preserving UTF-8 Metal embedding; --check never writes files."""
import argparse
from pathlib import Path


def generate(raw):
    raw.decode("utf-8")  # Validate without newline translation or re-encoding.
    escapes = {9: r"\t", 10: r"\n", 13: r"\r", 34: r'\"',
               63: r"\077", 92: r"\\"}  # Escape '?' to avoid C trigraphs.
    literals = []
    for chunk in raw.splitlines(keepends=True) or [b""]:
        text = "".join(escapes.get(b) or
                       (chr(b) if 32 <= b < 127 else "\\%03o" % b)
                       for b in chunk)
        literals.append('    "' + text + '"\n')
    return ("/* Generated by Scripts/generate_shader.py; do not edit. */\n"
            "const char *NLDustMetalSource =\n" +
            "".join(literals).rstrip("\n") + ";\n").encode("ascii")


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=root / "src/DustShader.metal")
    parser.add_argument("--output", type=Path, default=root / "src/DustShaderSource.m")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.input.resolve() == args.output.resolve():
        parser.error("input and output must differ")
    try:
        expected = generate(args.input.read_bytes())
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != expected:
                parser.exit(1, "generated shader missing or stale: %s\n" % args.output)
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
    except (OSError, UnicodeError) as error:
        parser.exit(1, "generate_shader: %s\n" % error)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
